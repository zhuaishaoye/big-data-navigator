function hashNumber(value) {
  return crypto.createHash("sha1").update(String(value)).digest().readUInt32BE(0);
}

function rotate(items, seed) {
  if (!items.length) return [];
  const offset = seed % items.length;
  return [...items.slice(offset), ...items.slice(0, offset)];
}

function fence(language, code) {
  return `\`\`\`${language}\n${String(code).trim()}\n\`\`\``;
}

function tableCell(value) {
  return String(value).replaceAll("|", "\\|").replaceAll("\n", " ");
}

function metricOf(profile, offset = 0) {
  if (profile.specialty?.metric && offset === 0) return profile.specialty.metric;
  const metrics = profile.context.metricDefs || [["业务完成量", "COUNT(DISTINCT event_id)", "event_cnt"]];
  const metric = metrics[(profile.seed + offset) % metrics.length];
  return {
    name: metric[0],
    formula: metric[1],
    alias: metric[2],
    interpretation: "需要与对象、时间窗、状态和排除条件一起解释",
    trap: profile.context.risks?.[offset % Math.max(profile.context.risks.length, 1)] || "口径漂移"
  };
}

function entityOf(profile, offset = 0) {
  const entities = profile.context.entities || [["业务对象", "object_id"]];
  return entities[(profile.seed + offset) % entities.length];
}

function dimsOf(profile, count = 3) {
  const dims = profile.context.dims || ["业务分类", "时间", "状态"];
  return Array.from({ length: Math.min(count, dims.length) }, (_, index) => (
    dims[(profile.seed + index) % dims.length]
  ));
}

function familyGroup(profile) {
  const family = profile.specialty?.family || "";
  if (/finance/.test(family)) return "finance";
  if (/retail|order|growth/.test(family)) return "retail";
  if (/manufactur/.test(family)) return "manufacturing";
  if (/clinical|genomic|medical|pharma/.test(family)) return "healthcare";
  if (/kafka|spark|streaming|cdc|scheduling|warehouse|architecture|performance|sql|data-service/.test(family)) return "engineering";
  if (/agent|rag|llm|ml|ai-/.test(family)) return "ai";
  if (/quality|lineage|master-data|security/.test(family)) return "governance";
  if (/career|resume/.test(family)) return "career";
  if (/learning/.test(family)) return "learning";
  if (/data-project/.test(family)) return "project";
  if (profile.kind === "career" || profile.kind === "resume") return "career";
  if (profile.kind === "learning") return "learning";
  if (profile.kind === "project") return "project";
  if (profile.kind === "governance") return "governance";
  if (profile.kind === "ai") return "ai";
  if (profile.kind === "engineering") return "engineering";
  if (profile.kind === "industry") return "industry";
  return "analytics";
}

function profileSummary(profile) {
  const metric = metricOf(profile);
  const entity = entityOf(profile);
  return {
    metric,
    entity,
    dims: dimsOf(profile),
    system: (profile.specialty?.systems || profile.context.systems || []).slice(0, 4),
    control: (profile.specialty?.controls || profile.context.controls || [])[0] || "对象与状态唯一",
    risk: (profile.specialty?.risks || profile.context.risks || [])[0] || "口径不一致"
  };
}

